// Regenerates DECISIONS.md, the index of the decisions log, from decisions/.
// Each entry is its own file there, decisions/YYYY-MM-DD-slug.md, starting with
// a "## YYYY-MM-DD: Title" heading. Run after adding one: node scripts/decisions-index.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIR = 'decisions';
const OUT = 'DECISIONS.md';
const HOOK_MAX = 140;

const entries = readdirSync(DIR)
  .filter((name) => name.endsWith('.md'))
  .sort()
  .reverse()
  .map((name) => {
    const path = join(DIR, name);
    const text = readFileSync(path, 'utf8');
    const file = name.match(/^(\d{4}-\d{2}-\d{2})-[a-z0-9]+(?:-[a-z0-9]+)*\.md$/);
    if (!file) fail(`${path}: name it YYYY-MM-DD-slug.md (lowercase words joined by hyphens)`);
    const heading = text.match(/^## (\d{4}-\d{2}-\d{2}): (.+)$/m);
    if (!heading) fail(`${path}: the first line must be "## YYYY-MM-DD: Title"`);
    if (heading[1] !== file[1]) fail(`${path}: the heading date ${heading[1]} does not match the file name`);
    return { path, title: `${heading[1]}: ${heading[2].trim()}`, hook: hook(text) };
  });

// The hook is the first sentence of the entry's first bullet, with bold markers removed.
function hook(text) {
  const bullet = text.split('\n').find((line) => line.startsWith('- '));
  if (!bullet) return '';
  const plain = bullet.slice(2).replace(/\*\*/g, '').trim();
  let sentence = plain.split(/(?<=[.!?])\s/)[0];
  if (sentence.length > HOOK_MAX) sentence = sentence.slice(0, HOOK_MAX).replace(/\s+\S*$/, '') + '…';
  return sentence;
}

function fail(message) {
  console.error(message);
  process.exit(1);
}

const lines = [
  '# Decisions',
  '',
  `A short log of choices made and why, newest first. Each entry is its own file in \`${DIR}/\`, named \`YYYY-MM-DD-slug.md\`, so two branches can each add one without conflicting. To add an entry, create a new file there and run \`node scripts/decisions-index.mjs\`, which regenerates this index. Do not edit this file by hand.`,
  '',
  ...entries.map((e) => `- [${e.title}](${e.path}) ${e.hook}`.trimEnd()),
  '',
];
writeFileSync(OUT, lines.join('\n'));
console.log(`${OUT}: ${entries.length} entries`);
